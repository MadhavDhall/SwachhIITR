export const DEMO_WASTE_RECORDS: WasteRecord[] = DEMO_WASTE_SCANS.flatMap((scan) =>
  Object.entries(scan.classCounts).map(([cls, count]) => {
    const cat = WASTE_CATEGORIES.find((c) => c.name === cls) ?? WASTE_CATEGORIES[WASTE_CATEGORIES.length - 1];
    return {
      id: `wr_${scan.id}_${cls.replace(/\s/g, "_").toLowerCase()}`,
      scanId: scan.id,
      wasteClass: cls,
      count,
      confidence: scan.detections.filter((d) => d.class === cls).reduce((a, d) => a + d.confidence, 0) / count,
      recommendation: cat.recommendation,
      createdAt: scan.createdAt,
    };
  })
);

