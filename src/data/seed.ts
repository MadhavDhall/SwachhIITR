// ── Sensor Readings (recent history for bin_001) ───────────
function generateReadings(binId: string, baseFill: number, count: number): SensorReading[] {
  const readings: SensorReading[] = [];
  const now = Date.now();
  for (let i = count; i >= 0; i--) {
    const timestamp = new Date(now - i * 30 * 60000).toISOString();
    const fillPct = Math.min(100, Math.max(0, baseFill + (count - i) * 1.2 + (Math.random() - 0.3) * 4));
    const distanceCm = 120 - (fillPct / 100) * 115;
    readings.push({
      id: `rd_${binId}_${i}`,
      binId,
      timestamp,
      distanceCm: Math.round(distanceCm * 10) / 10,
      fillPct: Math.round(fillPct * 10) / 10,
      batteryPct: Math.round(95 - i * 0.2),
      rssi: Math.round(-60 - Math.random() * 20),
      isSimulated: true,
    });
  }
  return readings;
}

